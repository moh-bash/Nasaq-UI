import { themeRef } from '../shared/colors.js';
import { NQ, tabsAlign, tabsVariant } from '../shared/classNames.js';

/* generateTabsCSS(config, theme) -> Tabs.css source string.
   Mirrors the library stylesheet and scopes itself to @layer nasaq so an
   exported file has exactly the same cascade as the live preview. */

const sel = (name) => `.${name}`;

const color = (config, key, token, theme) => config.colors?.[key] || themeRef(token, theme);

export function generateTabsCSS(config, theme = {}) {
  const { layout, animation } = config;
  const active = color(config, 'active', 'primary', theme);
  const text = color(config, 'text', 'text', theme);
  const muted = color(config, 'muted', 'text-muted', theme);
  const border = color(config, 'border', 'border', theme);
  const panel = color(config, 'panel', 'surface', theme);
  const list = `${sel(NQ.tabsList)}`;
  const button = `${list} button`;
  const selected = `${button}[aria-selected='true']`;

  const out = [];
  const push = (line = '') => out.push(line);

  push('/* Tabs.css — generated by Nasaq UI. Pairs with Tabs.jsx. */');
  push();
  push(`${sel(NQ.tabs)} {`);
  push(`  --tabs-active: ${active};`);
  push(`  --tabs-text: ${text};`);
  push(`  --tabs-muted: ${muted};`);
  push(`  --tabs-border: ${border};`);
  push(`  --tabs-panel: ${panel};`);
  push(`  --tabs-gap: ${layout.gap}px;`);
  push('  color: var(--tabs-text);');
  push('}');
  push();
  push(list + ' {');
  push('  display: flex;');
  push('  align-items: center;');
  push('  justify-content: flex-start;');
  push('  gap: 8px;');
  push('  overflow-x: auto;');
  push('}');
  push();

  for (const align of ['start', 'center', 'end', 'stretch']) {
    const value = align === 'center' ? 'center' : align === 'end' ? 'flex-end' : align === 'stretch' ? 'stretch' : 'flex-start';
    push(`${sel(tabsAlign(align))} ${list} {`);
    push(`  justify-content: ${value};`);
    push('}');
    push();
  }
  push(`${sel(tabsAlign('stretch'))} ${button} {`);
  push('  flex: 1 1 0;');
  push('}');
  push();

  push(button + ' {');
  push('  flex: 0 0 auto;');
  push('  border: 0;');
  push('  color: var(--tabs-muted);');
  push('  background: transparent;');
  push('  cursor: pointer;');
  push('  font: inherit;');
  push('  padding: 10px 14px;');
  push(`  transition: color ${animation.duration}ms ${animation.easing}, background-color ${animation.duration}ms ${animation.easing}, border-color ${animation.duration}ms ${animation.easing};`);
  push('}');
  push();
  push(`${button}:hover:not(:disabled),`);
  push(selected + ' {');
  push('  color: var(--tabs-active);');
  push('}');
  push();
  push(`${button}:focus-visible {`);
  push(`  outline: 2px solid ${themeRef('focus', theme)};`);
  push('  outline-offset: 2px;');
  push('}');
  push();
  push(`${button}:disabled {`);
  push('  cursor: not-allowed;');
  push('  opacity: 0.45;');
  push('}');
  push();

  const underline = sel(tabsVariant('underline'));
  push(`${underline} ${list} {`);
  push('  border-bottom: 1px solid var(--tabs-border);');
  push('}');
  push();
  push(`${underline} ${selected} {`);
  push('  box-shadow: inset 0 -2px 0 var(--tabs-active);');
  push('}');
  push();

  const pill = sel(tabsVariant('pill'));
  push(`${pill} ${button} {`);
  push(`  border-radius: ${layout.radius}px;`);
  push('}');
  push();
  push(`${pill} ${selected} {`);
  push('  background: var(--tabs-active);');
  push('  color: var(--color-on-solid, #ffffff);');
  push('}');
  push();

  const boxed = sel(tabsVariant('boxed'));
  push(`${boxed} ${list} {`);
  push('  padding: 4px;');
  push('  border: 1px solid var(--tabs-border);');
  push(`  border-radius: ${layout.radius}px;`);
  push('  background: color-mix(in srgb, var(--tabs-panel) 88%, var(--tabs-border));');
  push('}');
  push();
  push(`${boxed} ${button} {`);
  push(`  border-radius: ${Math.min(layout.radius, 10)}px;`);
  push('}');
  push();
  push(`${boxed} ${selected} {`);
  push('  background: var(--tabs-panel);');
  push('  box-shadow: 0 1px 3px rgba(20, 22, 26, 0.12);');
  push('}');
  push();

  push(`${sel(NQ.tabsPanel)} {`);
  push('  margin-top: var(--tabs-gap);');
  push('  padding: 20px;');
  push('  border: 1px solid var(--tabs-border);');
  push(`  border-radius: ${layout.radius}px;`);
  push('  background: var(--tabs-panel);');
  push('  line-height: 1.6;');
  push('}');
  push();
  push(`${sel(NQ.tabsEmpty)} {`);
  push('  color: var(--tabs-muted);');
  push('}');
  push();
  push('@media (prefers-reduced-motion: reduce) {');
  push(`  ${button} {`);
  push('    transition-duration: 0.01ms;');
  push('  }');
  push('}');

  return ['@layer nasaq {', ...out, '}'].join('\n');
}
