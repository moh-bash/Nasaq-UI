import { themeRef } from '../shared/colors.js';

const color = (config, key, token, theme) => config.colors?.[key] || themeRef(token, theme);

export function generateTabsCSS(config, theme = {}) {
  const { layout, animation } = config;
  const active = color(config, 'active', 'primary', theme);
  const text = color(config, 'text', 'text', theme);
  const muted = color(config, 'muted', 'text-muted', theme);
  const border = color(config, 'border', 'border', theme);
  const panel = color(config, 'panel', 'surface', theme);
  return `/* Tabs.css - generated by Nasaq UI */
.tabs {
  --tabs-active: ${active};
  --tabs-text: ${text};
  --tabs-muted: ${muted};
  --tabs-border: ${border};
  --tabs-panel: ${panel};
  --tabs-gap: ${layout.gap}px;
  color: var(--tabs-text);
}
.tabs-list {
  display: flex;
  align-items: center;
  justify-content: ${layout.align === 'center' ? 'center' : layout.align === 'end' ? 'flex-end' : layout.align === 'stretch' ? 'stretch' : 'flex-start'};
  gap: 8px;
  overflow-x: auto;
}
.tabs-list button {
  flex: ${layout.align === 'stretch' ? '1' : '0 0 auto'};
  border: 0;
  color: var(--tabs-muted);
  background: transparent;
  cursor: pointer;
  font: inherit;
  padding: 10px 14px;
  transition: color ${animation.duration}ms ${animation.easing}, background-color ${animation.duration}ms ${animation.easing}, border-color ${animation.duration}ms ${animation.easing};
}
.tabs-list button:hover:not(:disabled),
.tabs-list button[aria-selected="true"] { color: var(--tabs-active); }
.tabs-list button:focus-visible {
  outline: 2px solid ${themeRef('focus', theme)};
  outline-offset: 2px;
}
.tabs-list button:disabled { cursor: not-allowed; opacity: .45; }
.tabs--underline .tabs-list { border-bottom: 1px solid var(--tabs-border); }
.tabs--underline .tabs-list button[aria-selected="true"] { box-shadow: inset 0 -2px 0 var(--tabs-active); }
.tabs--pill .tabs-list button { border-radius: ${layout.radius}px; }
.tabs--pill .tabs-list button[aria-selected="true"] { background: var(--tabs-active); color: #fff; }
.tabs--boxed .tabs-list { padding: 4px; border: 1px solid var(--tabs-border); border-radius: ${layout.radius}px; background: color-mix(in srgb, var(--tabs-panel) 88%, var(--tabs-border)); }
.tabs--boxed .tabs-list button { border-radius: ${Math.min(layout.radius, 10)}px; }
.tabs--boxed .tabs-list button[aria-selected="true"] { background: var(--tabs-panel); box-shadow: 0 1px 3px rgba(20, 22, 26, .12); }
.tabs-panel { margin-top: var(--tabs-gap); padding: 20px; border: 1px solid var(--tabs-border); border-radius: ${layout.radius}px; background: var(--tabs-panel); line-height: 1.6; }
.tabs-empty { color: var(--tabs-muted); }
@media (prefers-reduced-motion: reduce) { .tabs-list button { transition-duration: .01ms; } }
`;
}
