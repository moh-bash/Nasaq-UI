/*
  Button — a reusable action control.

  Structure, semantics and state live here; every appearance value lives in the
  matching Button.css (generated by the playground). Variant and size are plain
  classes so the same component works with hand-written CSS too.

  <Button
    variant="primary"     // primary | secondary | outline | ghost | danger
    size="md"             // sm | md | lg
    fullWidth={false}
    align="start"         // start | center | end
    loading={false}
    disabled={false}
    leadingIcon={<svg … />}
    trailingIcon={<svg … />}
  >
    Create project
  </Button>
*/

export default function Button({
  variant = 'primary',
  size = 'md',
  fullWidth = false,
  align = 'start',
  disabled = false,
  loading = false,
  leadingIcon = null,
  trailingIcon = null,
  type = 'button',
  className = '',
  children,
  ...rest
}) {
  const classes = [
    'btn',
    `btn--${variant}`,
    `btn--${size}`,
    fullWidth ? 'btn--full' : `btn--align-${align}`,
    loading ? 'is-loading' : '',
    className,
  ]
    .filter(Boolean)
    .join(' ');

  const hasLeading = Boolean(leadingIcon) || loading;
  const hasTrailing = Boolean(trailingIcon) && !loading;

  return (
    <button
      type={type}
      className={classes}
      disabled={disabled || loading}
      aria-busy={loading ? 'true' : undefined}
      {...rest}
    >
      {loading ? (
        <span className="btn__spinner" aria-hidden="true" />
      ) : hasLeading ? (
        <span className="btn__icon" aria-hidden="true">
          {leadingIcon}
        </span>
      ) : null}
      {children ? <span className="btn__label">{children}</span> : null}
      {hasTrailing ? (
        <span className="btn__icon" aria-hidden="true">
          {trailingIcon}
        </span>
      ) : null}
    </button>
  );
}
